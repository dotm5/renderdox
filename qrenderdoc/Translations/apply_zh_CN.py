PLACEHOLDER = re.compile(r"%(?:\d+|n)")
PROTECTED = re.compile(
    r"\b(?:EID|VS|PS|FS|CS|GS|HS|DS|IA|RS|OM|ResourceId|SPIR-V|DXBC|DXIL|GLSL|HLSL)\b"
)


def validate(source: str, translation: str) -> None:
    if Counter(PLACEHOLDER.findall(source)) != Counter(PLACEHOLDER.findall(translation)):
        raise ValueError(f"placeholder mismatch: {source!r} -> {translation!r}")
    for token in PROTECTED.findall(source):
        if token not in translation:
            raise ValueError(f"protected token {token!r} missing: {source!r}")


def main() -> int:
    ts_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("qrenderdoc_zh_CN.ts")
    tree = ET.parse(ts_path)
    root = tree.getroot()
    applied = 0
    per_context: dict[str, tuple[int, int]] = {}

    for context in root.findall("context"):
        name = context.findtext("name", default="")
        reviewed = dict(GLOBAL)
        reviewed.update(CONTEXT.get(name, {}))
        translated_count = 0
        total = 0

        for message in context.findall("message"):
            total += 1
            source = message.findtext("source", default="")
            translation_text = reviewed.get(source)
            translation = message.find("translation")
            if translation_text is None or translation is None:
                if translation is not None and not (translation.text or "").strip():
                    translation.set("type", "unfinished")
                continue

            validate(source, translation_text)
            translation.attrib.pop("type", None)
            translation.clear()
            translation.text = translation_text
            applied += 1
            translated_count += 1

        per_context[name] = (translated_count, total)

    ET.indent(root, space="  ")
    body = ET.tostring(root, encoding="utf-8")
    ts_path.write_bytes(b'<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>\n' + body + b"\n")

    print(f"applied={applied}")
    for name in (
        "SettingsDialog",
        "MainWindow",
        "CaptureDialog",
        "EventBrowser",
        "TextureViewer",
        "BufferViewer",
        "PipelineStateViewer",
        "ResourceInspector",
    ):
        translated, total = per_context.get(name, (0, 0))
        print(f"{name}={translated}/{total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
